#!/usr/bin/env python3
"""Script de sincronización de invariantes financieras de Open Payments.

Copia una versión compacta y normalizada de las invariantes de negocio
definidas en .agents/rules/10-payments-domain.md a references/invariants.md
en cada skill que las requiera, marcándolas con una cabecera autogenerada.
"""

import argparse
import os
import sys

HEADER = "<!-- AUTOGENERATED BY scripts/sync-shared.py - DO NOT EDIT -->\n"

COMPACT_INVARIANTS = """# Invariantes Financieras de Dominio (Open Payments)

Este documento contiene las reglas de negocio e invariantes obligatorias para operaciones financieras.

## 1. Precisión Numérica y Moneda
- Cero Floats: Todo valor monetario debe representarse como entero en su unidad mínima (`value` como string entero o bigint).
- Tupla Monetaria Obligatoria: Toda entidad de monto debe asociar `value`, `assetCode` (ej. ISO 4217) y `assetScale`.
- Prohibido el uso de tipos de coma flotante nativos para cálculos intermedios o conversiones.

## 2. Máquina de Estados de Pagos
- Estados formales: `PENDING`, `AUTHORIZED`, `PROCESSING`, `COMPLETED`, `FAILED`, `CANCELLED`.
- El estado `COMPLETED` se alcanza ÚNICAMENTE tras confirmación criptográfica o webhook verificado de Rafiki/Open Payments. Nunca asumas pago completado al crear la transferencia.

## 3. Idempotencia y Reintentos
- Toda solicitud saliente que debite fondos o inicie pagos debe incluir una `Idempotency-Key` única y determinista.
- Prohibido reintentar débitos a ciegas sin verificar el estado del intento previo persistido.

## 4. Aislamiento Criptográfico y Auditoría
- Claves privadas de firma residen exclusivamente en módulos protegidos con directiva `server-only`.
- Prohibido registrar claves privadas, tokens de acceso o datos confidenciales en consola o tablas de auditoría.
"""

TARGET_SKILLS = [
    "open-payments-transfers",
    "incoming-payments-checkout",
    "rafiki-local-playground",
    "server-only-payments-client",
    "webhook-signature-verification",
]


def sync_invariants(repo_root):
    skills_root = os.path.join(repo_root, ".agents", "skills")
    if not os.path.isdir(skills_root):
        print(f"ERROR: Directorio {skills_root} no existe.")
        return 1

    content = HEADER + "\n" + COMPACT_INVARIANTS
    count = 0

    for s_name in TARGET_SKILLS:
        s_dir = os.path.join(skills_root, s_name)
        if os.path.isdir(s_dir):
            ref_dir = os.path.join(s_dir, "references")
            os.makedirs(ref_dir, exist_ok=True)
            target_file = os.path.join(ref_dir, "invariants.md")
            with open(target_file, "w", encoding="utf-8") as f:
                f.write(content)
            count += 1
            print(f"Sincronizado: {target_file}")

    print(f"OK: Invariantes sincronizadas en {count} skills.")
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="Sincroniza invariantes financieras a references/invariants.md en skills de pagos."
    )
    parser.add_argument(
        "--root",
        default=".",
        help="Ruta raíz del repositorio (por defecto: .)",
    )
    args = parser.parse_args()
    sys.exit(sync_invariants(os.path.abspath(args.root)))


if __name__ == "__main__":
    main()
